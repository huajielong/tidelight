async (page) => {
  const base = page.url().split('/').slice(0, 3).join('/');
  const results = [];
  const errors = [];
  const failedResources = [];
  const check = (condition, name, detail = '') => {
    if (!condition) throw new Error(`FAIL: ${name}: ${detail}`);
    results.push({ name, result: 'pass', detail });
  };
  const observe = p => {
    p.on('pageerror', error => errors.push(error.message));
    p.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    p.on('response', response => { if (response.status() >= 400) failedResources.push(`${response.status()} ${response.url()}`); });
  };
  const ready = async p => {
    await p.waitForFunction(() => !!window.__TIDELIGHT__);
    await p.waitForFunction(() => Object.values(window.__TIDELIGHT__.getMetrics().assets).every(status => status === 'ready'));
  };
  const state = p => p.evaluate(() => window.__TIDELIGHT__.getState());
  observe(page);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + '/');
  await ready(page);
  check((await state(page)).phase === 'title', 'Title starts without countdown');
  check(await page.evaluate(() => !('step' in window.__TIDELIGHT__) && !('setSeed' in window.__TIDELIGHT__) && !('setInput' in window.__TIDELIGHT__)), 'Production API excludes test mutations');
  await page.screenshot({ path: '.logs/screenshots/title-desktop.png' });
  await page.locator('#start-button').click();
  const start = await state(page);
  check(start.phase === 'playing' && start.lives === 3, 'Start button enters play with three lives');
  await page.keyboard.down('d');
  await page.waitForFunction(x => window.__TIDELIGHT__.getState().player.x > x + 45, start.player.x);
  await page.keyboard.up('d');
  check((await state(page)).player.x > start.player.x + 45, 'Actual WASD input moves boat');
  await page.keyboard.press('Space');
  await page.waitForFunction(() => window.__TIDELIGHT__.getState().player.dashCooldown > 0);
  check(await page.locator('#dash-button').isDisabled(), 'Space dash starts cooldown and disables button');
  await page.keyboard.press('p');
  const paused = await state(page);
  await page.evaluate(() => new Promise(resolve => setTimeout(resolve, 250)));
  check((await state(page)).timeLeft === paused.timeLeft && paused.phase === 'paused', 'Pause freezes countdown');
  check(await page.locator('#resume-button').evaluate(node => node === document.activeElement), 'Pause focuses Resume');
  await page.keyboard.press('Enter');
  check((await state(page)).phase === 'playing', 'Enter on Resume resumes without accidental restart');
  await page.keyboard.press('m');
  check((await state(page)).muted && await page.locator('#mute-button').getAttribute('aria-pressed') === 'true', 'M toggles mute and accessible state');
  await page.keyboard.press('m');
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  check((await state(page)).phase === 'paused', 'Window blur automatically pauses');
  await page.locator('#resume-button').click();
  const beforeMouse = await state(page);
  const rect = await page.locator('#game-canvas').boundingBox();
  await page.mouse.move(rect.x + rect.width * 0.75, rect.y + rect.height * 0.75);
  await page.mouse.down();
  await page.waitForFunction(y => window.__TIDELIGHT__.getState().player.y > y + 35, beforeMouse.player.y);
  await page.mouse.up();
  check(!(await state(page)).pointer.active, 'Mouse drag moves in world space and releases');
  await page.screenshot({ path: '.logs/screenshots/playing-desktop.png' });

  await page.goto(base + '/?test=1');
  await ready(page);
  await page.evaluate(() => window.__TIDELIGHT__.loadScenario('collection'));
  await page.keyboard.down('ArrowRight');
  await page.evaluate(() => window.__TIDELIGHT__.step(400));
  await page.keyboard.up('ArrowRight');
  const collection = await state(page);
  check(collection.collected === 1 && collection.score === 100 && collection.combo === 1, 'Arrow movement collects fixture and increments score/combo/count');
  check(await page.locator('#score-value').textContent() === '000100' && await page.locator('#combo-count').textContent() === '1', 'HUD agrees with collection snapshot');
  await page.evaluate(() => window.__TIDELIGHT__.step(2600));
  check((await state(page)).combo === 0, 'Combo window expires');
  await page.evaluate(() => window.__TIDELIGHT__.loadScenario('damage'));
  await page.keyboard.down('d');
  await page.evaluate(() => window.__TIDELIGHT__.step(400));
  await page.keyboard.up('d');
  const damage = await state(page);
  check(damage.lives === 2 && damage.player.invulnerable > 0, 'Actual movement into shadow loses one life and gains hit immunity');
  await page.evaluate(() => window.__TIDELIGHT__.step(200));
  check((await state(page)).lives === 2, 'Hit immunity prevents immediate repeated damage');
  await page.screenshot({ path: '.logs/screenshots/damage-desktop.png' });
  await page.evaluate(() => window.__TIDELIGHT__.loadScenario('last-life'));
  await page.keyboard.down('d');
  await page.evaluate(() => window.__TIDELIGHT__.step(400));
  await page.keyboard.up('d');
  check((await state(page)).phase === 'gameover' && (await state(page)).endReason === 'lives', 'Last-life collision ends the run');
  await page.keyboard.press('Enter');
  check((await state(page)).phase === 'playing' && (await state(page)).lives === 3, 'Enter on result restarts cleanly');
  await page.evaluate(() => window.__TIDELIGHT__.loadScenario('survival'));
  await page.evaluate(() => window.__TIDELIGHT__.step(75000));
  const finished = await state(page);
  check(finished.phase === 'gameover' && finished.timeLeft === 0 && finished.elapsed === 75 && finished.endReason === 'time', 'Full 75-second survival ends at exact timeout');
  check(await page.locator('#final-survival').textContent() === '平安归岸 · 75 秒', 'Result reports survival');
  await page.screenshot({ path: '.logs/screenshots/result-desktop.png' });
  await page.locator('#restart-button').click();
  check((await state(page)).score === 0 && (await state(page)).collected === 0, 'Restart resets collection and score');
  const seedReplay = await page.evaluate(() => {
    const api = window.__TIDELIGHT__;
    api.setSeed(42); api.start(); api.setInput(1, 0); api.step(1000); const a = api.getState();
    api.restart(); api.setInput(1, 0); api.step(1000); const b = api.getState();
    const original = api.getState(); const altered = api.getState(); altered.player.x = -100;
    return { same: JSON.stringify(a) === JSON.stringify(b), detached: api.getState().player.x === original.player.x };
  });
  check(seedReplay.same && seedReplay.detached, 'Seed replay deterministic and snapshots detached');
  await page.evaluate(() => window.__TIDELIGHT__.loadScenario('empty'));
  await page.locator('#dash-button').click();
  await page.evaluate(() => window.__TIDELIGHT__.step(50));
  check((await state(page)).player.dashCooldown > 2, 'Clickable dash control uses same cooldown');

  for (const size of [{ width: 390, height: 844 }, { width: 320, height: 568 }, { width: 844, height: 390 }, { width: 720, height: 450 }]) {
    await page.setViewportSize(size);
    await page.evaluate(() => window.__TIDELIGHT__.restart());
    const layout = await page.evaluate(() => {
      const ids = ['game-canvas', 'score-value', 'combo-value', 'time-value', 'lives-value', 'mute-button', 'pause-button', 'dash-button'];
      const rect = document.getElementById('game-canvas').getBoundingClientRect();
      const visible = ids.every(id => {
        const node = document.getElementById(id), r = node.getBoundingClientRect();
        return r.width > 0 && r.height > 0 && r.left >= 0 && r.right <= innerWidth + 1 && r.top >= 0 && r.bottom <= innerHeight + 1 && getComputedStyle(node).visibility !== 'hidden';
      });
      return { visible, ratio: rect.width / rect.height, overflow: document.documentElement.scrollWidth > innerWidth, controls: ['mute-button', 'pause-button', 'dash-button'].map(id => { const r = document.getElementById(id).getBoundingClientRect(); return [r.width, r.height]; }) };
    });
    check(layout.visible && !layout.overflow && Math.abs(layout.ratio - 16 / 9) < 0.01 && layout.controls.every(([w, h]) => w >= 44 && h >= 44), `Layout ${size.width}×${size.height}`, JSON.stringify(layout));
    await page.screenshot({ path: `.logs/screenshots/playing-${size.width}x${size.height}.png` });
    await page.keyboard.press('p');
    check(await page.locator('#resume-button').isVisible(), `Pause menu usable at ${size.width}×${size.height}`);
  }

  const browser = page.context().browser();
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobile = await mobileContext.newPage(); observe(mobile);
  await mobile.goto(base + '/?test=1'); await ready(mobile);
  await mobile.touchscreen.tap(...await mobile.locator('#start-button').evaluate(node => { const r = node.getBoundingClientRect(); return [r.x + r.width / 2, r.y + r.height / 2]; }));
  check((await state(mobile)).phase === 'playing', 'Real touch starts game');
  await mobile.evaluate(() => window.__TIDELIGHT__.loadScenario('empty'));
  const mobileRect = await mobile.locator('#game-canvas').boundingBox();
  const session = await mobileContext.newCDPSession(mobile);
  const touch = { x: mobileRect.x + mobileRect.width * 0.8, y: mobileRect.y + mobileRect.height * 0.7, id: 1 };
  const mobileStart = await state(mobile);
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [touch] });
  await mobile.evaluate(() => window.__TIDELIGHT__.step(400));
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...touch, x: touch.x - 10 }] });
  check((await state(mobile)).player.x > mobileStart.player.x + 20 && (await state(mobile)).pointer.active, 'Real touch drag steers through Pointer Events');
  await session.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  check(!(await state(mobile)).pointer.active, 'Touch cancel clears pointer');
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [touch] });
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  check(!(await state(mobile)).pointer.active, 'Touch release clears pointer');
  const mobileMetrics = await mobile.evaluate(() => window.__TIDELIGHT__.getMetrics());
  check(mobileMetrics.reducedMotion && mobileMetrics.canvas.dpr === 2, 'Reduced motion and high-DPR cap apply');
  await mobile.screenshot({ path: '.logs/screenshots/touch-reduced-motion-dpr3.png' });
  await mobileContext.close();
  check(errors.length === 0 && failedResources.length === 0, 'No runtime errors or failed resources', JSON.stringify({ errors, failedResources }));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + '/'); await ready(page);
  return { date: new Date().toISOString(), browser: 'Microsoft Edge via Playwright CLI', assertions: results.length, results, errors, failedResources };
}
